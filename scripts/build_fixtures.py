def build_social(
    rng: random.Random,
    models: dict[str, str],
    cities: list[str],
    range_templates: list[str],
    range_values: dict,
    clusters: dict,
    injection: dict,
    subreddit: str,
) -> tuple[list[dict], list[dict]]:
    reddit, youtube = [], []
    counter = 0

    def emit(round_label: str, text: str, title: str, brand: str | None) -> None:
        nonlocal counter
        counter += 1
        ts = stamp(rng, round_label)
        if counter % 3 == 0:
            vid = f"fxv{counter:05d}"
            youtube.append(
                {
                    "round": round_label,
                    "video_id": vid,
                    "video_title": f"{brand + ' ' + models[brand] if brand else 'Budget buyers'} long-term review (fixture)",
                    "comment_id": f"c{counter:04d}",
                    "text": text,
                    "published_at": ts,
                    "like_count": rng.randint(0, 120),
                }
            )
        else:
            pid = f"fx{counter:05d}"
            reddit.append(
                {
                    "round": round_label,
                    "id": pid,
                    "subreddit": subreddit,
                    "title": title,
                    "text": text,
                    "permalink": f"https://reddit.example/r/{subreddit}/comments/{pid}/",
                    "created_at": ts,
                    "score": rng.randint(1, 250),
                    "num_comments": rng.randint(0, 60),
                }
            )

    for brand, rounds in range_values.items():
        for round_label, values in rounds.items():
            for i, v in enumerate(values):
                tpl = range_templates[i % len(range_templates)]
                vv = f"{v:g}"
                text = tpl.format(
                    brand=brand, model=models[brand], v=vv, city=cities[i % len(cities)], weeks=rng.randint(3, 12)
                )
                title = RANGE_TITLES[(i + len(brand)) % len(RANGE_TITLES)].format(brand=brand, model=models[brand])
                emit(round_label, text, title, brand)
    for name, cl in clusters.items():
        for round_label, n in cl["counts"].items():
            for i in range(n):
                brand = cl["brands"][i % len(cl["brands"])]
                tpl = cl["templates"][i % len(cl["templates"])]
                b = brand or rng.choice(list(models))
                text = tpl.format(
                    brand=b, model=models[b], city=cities[(i + len(name)) % len(cities)], weeks=rng.randint(2, 6)
                )
                emit(round_label, text, f"{name.capitalize()} thread: {b} {models[b]}", brand)
    emit("current", injection["text"], injection["title"], None)
    return reddit, youtube


def build_metrics(spec: dict, path: Path, rng: random.Random) -> None:
    rows = []
    months = spec["months"]
    for brand, (base, growth, aug_growth) in spec["brands"].items():
        for r_i, region in enumerate(spec["regions"]):
            value = base * (0.85 + 0.1 * r_i)
            for m_i, month in enumerate(months):
                if m_i > 0:
                    g = aug_growth if month.endswith("-08") else growth
                    value *= 1 + g + rng.uniform(-0.004, 0.004)
                rows.append({"brand": brand, "region": region, "month": month, "units": round(value)})
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as fh:
        fh.write(f"# {NOTICE}\n")
        w = csv.DictWriter(fh, fieldnames=["brand", "region", "month", "units"])
        w.writeheader()
        w.writerows(rows)


def write_json(path: Path, items: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({"_notice": NOTICE, "items": items}, indent=1, ensure_ascii=False), encoding="utf-8")


def news_items(rng: random.Random, raw: list[dict]) -> list[dict]:
    out = []
    for i, n in enumerate(raw):
        as_of = dict(ROUNDS)[n["round"]]
        out.append(
            {
                "id": f"n{i + 1:02d}",
                "round": n["round"],
                "title": n["title"],
                "url": n["url"],
                "source_name": n["source_name"],
                "published_at": iso(as_of - timedelta(hours=n["h"])),
                "summary": n["content"].split(". ")[0] + ".",
                "content": n["content"],
                "is_primary": bool(n.get("is_primary")),
            }
        )
    return out


def build_workspace(name: str, spec: dict) -> None:
    rng = random.Random(f"fieldnote-{name}")
    root = ROOT / name
    manifest = {
        "_notice": NOTICE,
        "fixture": True,
        "rounds": [{"label": lbl, "as_of": iso(dt)} for lbl, dt in ROUNDS],
        "overlay": {
            "competitors": spec["competitors"],
            "connectors": [
                {
                    "type": "csv_file",
                    "name": spec["connector_name"],
                    "label": spec["connector_label"],
                    "path": "metrics.csv",
                    "mapping": {"entity": "brand", "region": "region", "period": "month", "value": "units"},
                    "unit": "units/month",
                    "source_url": f"https://data.example/{name}/fixture-dataset",
                }
            ],
        },
    }
    root.mkdir(parents=True, exist_ok=True)
    (root / "manifest.json").write_text(json.dumps(manifest, indent=1, ensure_ascii=False), encoding="utf-8")
    write_json(root / "news.json", news_items(rng, spec["news"]))
    write_json(
        root / "pages.json",
        [{"competitor": c, "url": u, "kind": k, "round": r, "html": h} for c, u, k, r, h in spec["pages"]],
    )
    reddit, youtube = build_social(
        rng,
        spec["models"],
        spec["cities"],
        spec["range_templates"],
        spec["range_values"],
        spec["clusters"],
        spec["injection"],
        spec["subreddit"],
    )
    write_json(root / "reddit.json", reddit)
    write_json(root / "youtube.json", youtube)
    build_metrics(spec["metrics"], root / "metrics.csv", rng)
    print(
        f"{name}: {len(spec['news'])} news, {len(spec['pages'])} page versions, {len(reddit)} reddit, {len(youtube)} youtube"
    )


